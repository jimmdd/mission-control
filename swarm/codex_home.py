"""A Codex home for Mission Control runs, without the operator's orchestration layers.

The operator's `~/.codex` carries oh-my-codex (a 28.8 KB global AGENTS.md, its
`developer_instructions`, notify and hooks) and oh-my-openagent's Light plugin. Both
are built for interactive sessions. Inside an MC ticket they are a second and third
orchestrator stacked on MC's own: every turn of MET-792 re-sent them, and the run
spent 54 of its 71 minutes thinking over a ~120k-token context.

This builds `$MC_HOME/codex-home` instead:

- `auth.json` and the plugin/browser runtime directories are symlinked, so logins,
  token refreshes and bundled tools (browser, computer use, Paper MCP) keep working;
- `config.toml` is the operator's, minus the orchestration layers;
- there is no global `AGENTS.md`, no `hooks.json`, no `agents/`, `skills/` or
  `prompts/` — the repository's own AGENTS.md files still load as usual.

The operator's terminal Codex is untouched: nothing here writes under `~/.codex`.
"""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path
from typing import List

# Runtime pieces tickets rely on. Everything else in ~/.codex is either session
# history (kept separate on purpose) or an orchestration layer (left out on purpose).
LINKED = ("auth.json", "plugins", "computer-use", "node_repl", "browser", "codex-lsp", "vendor_imports")

# Top-level keys that exist only to drive oh-my-codex.
DROP_KEYS = ("developer_instructions", "notify")

# Tables that belong to the orchestration layers. `[agents.*]` point at OMX/OMO role
# files that are not linked; `[hooks.*]` is trust state for their hooks; sisyphuslabs
# is oh-my-openagent's Light plugin.
DROP_TABLES = re.compile(
    r"^(agents(\..*)?|hooks(\..*)?|tui(\..*)?"
    r"|marketplaces\.sisyphuslabs"
    r"|plugins\.\"[^\"]*@sisyphuslabs\")$"
)

HEADER = re.compile(r"^\s*\[\[?\s*([^\]]+?)\s*\]\]?\s*(#.*)?$")


def filter_config(text: str) -> str:
    """The operator's config.toml without the orchestration layers.

    Line-based on purpose: TOML tables are delimited by header lines, and a real
    parser would drop the comments that tell a reader why each block exists.
    """
    out: List[str] = []
    in_top = True
    dropping = False
    skipping_value = False
    for line in text.splitlines():
        m = HEADER.match(line)
        if m:
            in_top = False
            dropping = bool(DROP_TABLES.match(m.group(1).strip()))
            skipping_value = False
            if not dropping:
                out.append(line)
            continue
        if dropping:
            continue
        if skipping_value:
            # A dropped key whose array value spans several lines.
            if line.rstrip().endswith("]"):
                skipping_value = False
            continue
        if in_top:
            key = line.split("=", 1)[0].strip() if "=" in line else ""
            if key in DROP_KEYS:
                value = line.split("=", 1)[1].strip()
                if value.startswith("[") and not value.rstrip().endswith("]"):
                    skipping_value = True
                continue
        out.append(line)
    header = ("# Generated by Mission Control from ~/.codex/config.toml (swarm/codex_home.py).\n"
              "# oh-my-codex / oh-my-openagent layers removed. Do not edit; it is rebuilt.\n")
    return header + "\n".join(out) + "\n"


def ensure(mc_home: Path, user_home: Path) -> Path:
    """Build or refresh the isolated home and return its path. Idempotent."""
    home = mc_home / "codex-home"
    home.mkdir(parents=True, exist_ok=True)
    for name in LINKED:
        src, dst = user_home / name, home / name
        if not src.exists():
            continue
        if dst.is_symlink() and os.readlink(dst) == str(src):
            continue
        if dst.is_symlink() or dst.exists():
            if dst.is_dir() and not dst.is_symlink():
                continue            # never delete a real directory someone put here
            dst.unlink()
        dst.symlink_to(src)
    src_cfg, dst_cfg = user_home / "config.toml", home / "config.toml"
    if src_cfg.exists():
        fresh = filter_config(src_cfg.read_text())
        if not dst_cfg.exists() or dst_cfg.read_text() != fresh:
            dst_cfg.write_text(fresh)
    return home


if __name__ == "__main__":
    # `python3 codex_home.py ensure` prints the path for run-codex.sh to export.
    if sys.argv[1:] != ["ensure"]:
        sys.exit("usage: codex_home.py ensure")
    mc = Path(os.environ.get("MC_HOME", str(Path.home() / ".mission-control")))
    print(ensure(mc, Path(os.environ.get("MC_USER_CODEX_HOME", str(Path.home() / ".codex")))))
